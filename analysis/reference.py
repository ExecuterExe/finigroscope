def is_parent(structure, index: int) -> bool:
    """True, если у раздела есть непосредственный подраздел (раздел-родитель).

    Родителя освобождаем от проверки наполненности: его текст — это его
    подразделы. Например, «4.» — родитель «4.1», «4.2»…
    """
    cur = leading_number(structure[index])
    if not cur or index + 1 >= len(structure):
        return False
    nxt = leading_number(structure[index + 1])
    return len(nxt) > len(cur) and nxt[: len(cur)] == cur


def parent_flags(structure):
    """Список булевых флагов «раздел-родитель» по индексам структуры."""
    return [is_parent(structure, i) for i in range(len(structure))]
