"""Нормализация текста — общая для сопоставления заголовков и извлечения значений.

Заголовки в документах участников гуляют по мелочам: разные кавычки («» / "" / "),
разные тире (-/–/—/−), ё вместо е, двойные пробелы. Чтобы сравнение с эталоном не
ломалось из-за этого, и эталон, и строку документа приводим к единому виду.
"""

import re

# карты замен спецсимволов на канонические
_QUOTES = {
    "«": '"', "»": '"', "“": '"', "”": '"', "„": '"', "‟": '"',
    "‘": "'", "’": "'", "‚": "'",
}
_DASHES = {"–": "-", "—": "-", "−": "-", "‐": "-", "‑": "-", "―": "-"}


def collapse_spaces(text: str) -> str:
    """Схлопывает любые пробельные последовательности в один пробел."""
    return " ".join((text or "").split())


def normalize(text: str) -> str:
    """Канонизирует текст для сравнения: кавычки, тире, ё→е, регистр, пробелы."""
    text = collapse_spaces(text)
    for src, dst in _QUOTES.items():
        text = text.replace(src, dst)
    for src, dst in _DASHES.items():
        text = text.replace(src, dst)
    text = text.replace("ё", "е").replace("Ё", "Е")
    return text.lower()


def leading_number(text: str):
    """Возвращает номер раздела как список int: «4.1» → [4, 1]; нет номера → []."""
    m = re.match(r"^\s*(\d+(?:\.\d+)*)", text or "")
    if not m:
        return []
    return [int(x) for x in m.group(1).split(".") if x != ""]
