"""Применение миграций схемы при старте сервиса.

Раньше схема поднималась одним `db.create_all()`. Это работает ровно один раз —
на пустом файле: `create_all` умеет создавать недостающие ТАБЛИЦЫ, но не умеет
добавлять колонки в уже существующие. Пока база стиралась при каждом запуске,
проблемы не было видно; с постоянным хранилищем (а без него интеграция по API
невозможна) любое новое поле молча не появилось бы, и сервис падал бы на
запросе к несуществующей колонке.

Три случая, которые здесь разведены:

1. **Пустой файл** — накатываем все миграции с нуля.
2. **База, созданная старым `create_all`** (таблицы есть, служебной
   `alembic_version` нет) — сначала доводим набор ТАБЛИЦ до текущих моделей,
   потом ставим отметку о ревизии.

   Порядок здесь не косметический. Первая версия этого кода просто «штамповала»
   такую базу, считая, что раз начальная миграция автогенерирована из тех же
   моделей, схема ей уже соответствует. Это неверно ровно для того случая, ради
   которого всё и затевалось: база, сделанная ДО появления новой таблицы, о ней
   не знает, а отметка говорит «всё применено» — и сервис падает на первом же
   запросе к несуществующей таблице. Проверено на себе при переходе на фоновые
   задачи: тестовая база осталась без `jobs`.

   Честная граница этого случая: недостающие ТАБЛИЦЫ мы добавим, а недостающие
   КОЛОНКИ в уже существующих таблицах — нет, их так не увидеть. Для унаследо-
   ванной базы это остаточный риск; для всех баз, созданных начиная с этой
   ревизии, его нет — они ведутся миграциями с самого начала.
3. **База под управлением Alembic** — обычный `upgrade head`.
"""

from __future__ import annotations

import os

from alembic import command
from alembic.config import Config
from sqlalchemy import inspect

import config

_HERE = os.path.dirname(os.path.abspath(__file__))


def _alembic_config() -> Config:
    cfg = Config(os.path.join(_HERE, "alembic.ini"))
    cfg.set_main_option("script_location", os.path.join(_HERE, "migrations"))
    cfg.set_main_option("sqlalchemy.url", config.database_uri())
    return cfg


def upgrade(db) -> str:
    """Приводит схему к последней ревизии. Возвращает, что именно было сделано."""
    inspector = inspect(db.engine)
    tables = set(inspector.get_table_names())
    cfg = _alembic_config()

    if not tables:
        command.upgrade(cfg, "head")
        return "создана с нуля миграциями"

    if "alembic_version" not in tables:
        # База досталась от прежней схемы через create_all. Выполнить миграцию
        # целиком нельзя — CREATE TABLE упадёт на уже существующих. Но и просто
        # пометить её нельзя: в ней может не быть таблиц, добавленных позже.
        # Поэтому сначала доводим состав таблиц, потом ставим отметку.
        db.create_all()
        db.session.commit()
        added = sorted(set(inspect(db.engine).get_table_names()) - tables
                       - {"alembic_version"})
        command.stamp(cfg, "head")
        if added:
            return ("унаследованная база: добавлены недостающие таблицы ("
                    + ", ".join(added) + "), поставлена отметка о ревизии")
        return "существующая база помечена текущей ревизией"

    command.upgrade(cfg, "head")
    return "миграции применены" + _heal_missing_tables(db)


def _heal_missing_tables(db) -> str:
    """Достраивает таблицы, которых нет в базе, хотя модели их объявляют.

    Страховка от расхождения «отметка о ревизии есть, а таблицы нет». Такое
    состояние получается, если базу когда-то пометили ревизией, не применив её
    (ровно эта ошибка была в первой версии модуля), или если файл правили
    руками. Само по себе оно не лечится `upgrade`: Alembic видит отметку и
    считает, что применять нечего, — а сервис падает на первом же запросе.

    Возвращает пустую строку, когда всё в порядке, иначе — что пришлось добавить.
    """
    existing = set(inspect(db.engine).get_table_names())
    declared = set(db.metadata.tables)
    missing = sorted(declared - existing)
    if not missing:
        return ""
    db.create_all()
    db.session.commit()
    return (f"; ВНИМАНИЕ: в базе не хватало таблиц ({', '.join(missing)}) при "
            "наличии отметки о ревизии — они достроены")
