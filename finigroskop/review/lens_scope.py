"""Какие линзы применимы к ОТДЕЛЬНОМУ модулю игры, а не к игре целиком.

Оценщик по линзам (review/lens_evaluator.py) писался под готовую игру: у него на
входе правила, компоненты, канонический текст автора и заметки трёх числовых
агентов. «Генератор игр» устроен иначе — он собирает игру по частям, и каждая
часть проходит проверку сразу, как только сделана (этапы 2–6 его ТЗ):

    механики → сюжет → особенности → компоненты → правила

Соблазнительно отдать линзам первый же модуль как есть. Делать так нельзя, и
причина не в аккуратности, а в арифметике итогового балла. Категории, которые
целиком ушли в N/A, выпадают И ИЗ ЧИСЛИТЕЛЯ, И ИЗ ЗНАМЕНАТЕЛЯ взвешенного
среднего (см. synthesizer.overall_score). Модуль механик не содержит ни
количества компонентов, ни сюжета — значит «Структурная целостность» и
«Реиграбельность и нарратив» выпали бы молча, а балл посчитался бы по
оставшимся категориям и выглядел бы точно так же, как балл полной игры. Число
солидное, а означает другое — худший из возможных исходов.

Поэтому область применимости объявляется ЯВНО и заранее: для каждого модуля
известно, какие категории он в принципе способен закрыть. Всё, что вне области,
не спрашивается у модели вовсе (незачем платить за 47 линз, когда осмысленны 20)
и честно показывается в ответе как непокрытый вес.

Область — данные, а не логика: состав модулей у генератора будет меняться ещё
долго, и поправить таблицу должно быть можно, не трогая код.
"""

from review.lens_evaluator import CORE

# --- какие категории закрывает каждый модуль --------------------------------
#
# Правило отбора одно: категория попадает в область, если модуль СОДЕРЖИТ
# материал для её оценки. Не «имеет к ней отношение», а именно содержит — иначе
# агент начнёт достраивать игру в уме, что запрещено первым же железным
# правилом промпта («оценивай только по присланным материалам»).
SCOPE = {
    # Этап 2. Игровой цикл, ядро механик, условие победы, роль случайности,
    # типы компонентов (без количества), поддержка отстающих.
    "mechanics": [
        "Механика и решения игрока",
        "Навык, шанс, напряжение",
        "Целостность дизайна и цели",
        # «Экономика и баланс» здесь оценивается КАК ЗАМЫСЕЛ — осмыслен ли обмен
        # ресурсов, понятна ли ценность наград. Числовую сторону в генераторе
        # пока не считает никто, и это отдельно помечается в ответе.
        "Экономика и баланс",
        "Социальное взаимодействие",
    ],
    # Этап 3. Название и сюжет поверх готовых механик.
    "story": [
        "Реиграбельность и нарратив",
        "Замысел и образовательная ценность",
        "Игрок, доступность, вовлечение",
    ],
    # Этап 4. Концепция, особенности, помощь отстающим.
    "features": [
        "Игрок, доступность, вовлечение",
        "Целостность дизайна и цели",
        "Социальное взаимодействие",
        "Замысел и образовательная ценность",
    ],
    # Этап 5. Количество компонентов и материалы — впервые появляется физический
    # интерфейс, который до этого оценивать было не по чему.
    "components": [
        "Структурная целостность и физический интерфейс",
        "Игрок, доступность, вовлечение",
    ],
    # Этап 6. Краткие правила и рекомендации: к этому моменту описание игры
    # накоплено целиком, поэтому область — всё ядро.
    "rules": list(CORE),
}

# --- чего модуль ЕЩЁ не содержит -------------------------------------------
#
# Самая дорогая ошибка модульной оценки — наказать модуль за отсутствие того,
# чего на его этапе не бывает. Она поймана на живом прогоне: модуль механик
# получил 4 из 10 в «Экономике и балансе» (вес 1.5, самая тяжёлая категория) с
# формулировкой «неизвестны стоимость элементов, выдача влияния, длина пути —
# баланс невозможно проверить». Всё верно: количества и стоимости появляются
# только на этапе 5, и содержать их модуль механик НЕ ИМЕЕТ ПРАВА.
#
# Ограничить состав категорий (SCOPE выше) оказалось мало. Внутри разрешённой
# категории агент всё равно видел пустоту и читал её как брак. Пустоту надо
# назвать вслух: вот чего здесь нет и когда оно появится.
#
# Правило само по себе не новое — в промпте есть «оценивай только по присланным
# материалам». Но оно про то, чего НЕ ДЕЛАТЬ, а модели нужно сказать, что
# делать вместо: N/A с причиной, а не низкий балл.
LATER_STAGES = {
    "mechanics": [
        ("количество компонентов, их материалы и любые числовые параметры "
         "(стоимости, размеры колод, длина пути)", "этап 5"),
        ("название игры и сюжет", "этап 3"),
        ("концепция, особенности игры и помощь отстающим", "этап 4"),
        ("краткие правила и рекомендации", "этап 6"),
    ],
    "story": [
        ("количество компонентов и материалы", "этап 5"),
        ("особенности игры и помощь отстающим", "этап 4"),
        ("краткие правила", "этап 6"),
    ],
    "features": [
        ("количество компонентов и материалы", "этап 5"),
        ("краткие правила", "этап 6"),
    ],
    "components": [
        ("краткие правила и рекомендации", "этап 6"),
    ],
    # Этап 6 — последний: к нему описание игры собрано целиком, и ссылаться на
    # «будущие этапы» больше не на что.
    "rules": [],
}

# Особые оговорки по категориям: где оценивать можно только ЗАМЫСЕЛ.
CATEGORY_NOTES = {
    "mechanics": {
        "Экономика и баланс":
            "числовой стороны на этом этапе не существует вовсе — оценивай "
            "только ЗАМЫСЕЛ обмена: осмысленны ли ресурсы, понятна ли ценность "
            "наград, есть ли выбор между тратой и накоплением. Отсутствие "
            "чисел не снижает балл и не является находкой.",
    },
}


def later_stages_for(phase):
    """Чего модуль ещё не содержит и на каком этапе появится."""
    return list(LATER_STAGES.get(phase) or [])


def category_notes_for(phase):
    return dict(CATEGORY_NOTES.get(phase) or {})


# Линзы обучающей цели. В ФинИгроСкопе им запрещён N/A: там всякая игра
# финансово-образовательная, и отсутствие обучающей цели — реальный дефект.
# Генератор делает игры любые, поэтому запрет включается по ответу на вопрос 1
# опросника, а не всегда (см. education_required).
EDUCATION_LENSES = (97, 98)

# Ответы вопроса 1 «основная цель игры», при которых игра считается обучающей.
# Строки — ровно как в опроснике (generator/app.js, Q01).
EDUCATIONAL_PURPOSES = ("Обучение", "Развитие навыков")


def known_phases():
    return sorted(SCOPE)


def categories_for(phase):
    """Категории, применимые к модулю. Пустой список — фаза неизвестна."""
    return list(SCOPE.get(phase) or [])


def core_for(phase):
    """Ядро линз модуля: {категория: [номера]} — подмножество полного CORE."""
    return {name: list(CORE[name]) for name in categories_for(phase) if name in CORE}


def education_required(params):
    """Запрещён ли N/A для линз 97/98 у ЭТОЙ игры.

    Решает ответ на вопрос 1 опросника, а не жанр и не сеттинг: обучающей игру
    делает заявленная цель. Если цель развлекательная, требовать обучающую
    ценность бессмысленно — игра получила бы низкий балл в самой тяжёлой
    категории (вес 1.5) за то, чего никогда и не обещала.
    """
    purposes = (params or {}).get("purpose") or []
    return any(p in EDUCATIONAL_PURPOSES for p in purposes)


def scope_for(phase, params=None):
    """Полное описание области для одного прохода.

    Отдаётся и в промпт (что спрашивать), и в валидатор (что требовать), и в
    расчёт балла (какой вес считать покрытым) — один источник истины на все три
    применения, иначе они разъедутся.
    """
    core = core_for(phase)
    lenses = sorted(n for nums in core.values() for n in nums)
    edu = education_required(params)
    return {
        "phase": phase,
        "core": core,
        "lenses": lenses,
        "later_stages": later_stages_for(phase),
        "category_notes": category_notes_for(phase),
        # N/A для 97/98 запрещён только у заявленно обучающей игры
        "education_lenses": EDUCATION_LENSES if edu else (),
        "educational": edu,
    }
