# -*- coding: utf-8 -*-
"""Детерминированные проверки, общие для генераторов модулей.

Сюда вынесено то, что обязаны проверять НЕСКОЛЬКО агентов одинаково. Причина
простая и проверенная на этом же проекте: две копии одного правила расходятся
со второй правки, и расходятся молча — оба агента продолжают работать, просто
запрещают разное.

Здесь только проверки, у которых есть однозначный ответ «да/нет». Всё, что
требует суждения («хороший ли это сюжет», «добавляют ли особенности глубину»),
кодом не проверяется вовсе — за это отвечают аудитор и линзы.
"""

import json
import re

# --- количество компонентов -------------------------------------------------
#
# По ТЗ количества считает программа на этапе 5. Названное раньше разойдётся с
# расчётным: программа посчитает своё, а в тексте у автора останется другое.

NUMBER_RE = (r"\b(\d+|один|одна|одно|два|две|три|четыре|пять|шесть|семь|"
             r"восемь|девять|десять)\s+")

# Родовые названия компонентов известны заранее.
COMPONENT_STEMS = ("карт", "жетон", "фишк", "кубик", "фигурк", "пол", "таймер")

# --- содержание не по возрасту ----------------------------------------------
#
# Возраст, ниже которого проверяем текст на пугающее. Не «мнение о детской
# психике», а следствие устройства конвейера: аудитор ловит это своим пунктом
# age_content_safe, но ловит МОДЕЛЬЮ, то есть иногда. Здесь дешёвая
# детерминированная страховка перед ним.
SCARY_AGE_LIMIT = 10

SCARY_WORDS = ("смерт", "убий", "убит", "кровь", "кровав", "труп", "казн",
               "пытк", "мучен", "ужас", "кошмар", "погиб", "мертв", "мёртв",
               "проклят", "жутк")


def extra_components_issues(variant, params, label):
    """Заявки модуля на дополнительные предметы. Возвращает (проблемы, замечания).

    Проверка живёт тут, а не в каждом агенте, по причине из шапки модуля: сюжет
    и особенности просят добавки одинаково, и два экземпляра одного правила
    разойдутся молча.

    ПОЧЕМУ ПОЧТИ ВСЁ — ЗАМЕЧАНИЯ, А НЕ ПРОБЛЕМЫ. Проблема означает «собрать
    модуль заново», то есть три платных вызова и минуты ожидания. Поле
    необязательное и добавочное: модуль без него полноценен, а с испорченной
    заявкой — полноценен ровно настолько же, только без одной добавки. Гонять
    из-за неё перегенерацию несоразмерно.

    Это не теория. Первая версия считала всё проблемами, и генерация
    особенностей перестала работать полностью: агент не получал списка
    выбранных компонентов (его не было в PARAM_KEYS), копировал пример из схемы,
    промахивался мимо невидимого ему списка — и ВСЕ три попытки браковались с
    «модель не собрала годный вариант». Список агенту теперь дают, но правило
    осталось: необязательное поле не вправе убить годный модуль.

    Проблемой остаётся одно — поле не список: это сломанный ответ, а не
    неудачная заявка.

    Негодные заявки не теряются: этап 5 отклоняет их повторно и показывает
    автору в rejected_extras с причиной.
    """
    from agents import components            # локально: избегаем цикла импорта

    warnings = []
    chosen = set(params.get("components") or [])
    rows = variant.get(components.EXTRA_FIELD)

    if rows is None:
        return [], warnings
    if not isinstance(rows, list):
        return ["%s: extra_components должно быть списком." % label], warnings

    for row in rows:
        if not isinstance(row, dict):
            warnings.append("%s: заявка на компоненты не объект: %r." % (label, row))
            continue

        name = str(row.get("component") or "").strip().lower()
        count = row.get("count")

        if not name:
            warnings.append("%s: в заявке не назван компонент — заявка не учтена."
                            % label)
        elif name not in chosen:
            warnings.append(
                "%s: заявлен компонент «%s», которого нет в ответах автора "
                "(выбраны: %s) — заявка не учтена."
                % (label, row.get("component"),
                   ", ".join(sorted(chosen)) or "ничего"))

        if isinstance(count, bool) or not isinstance(count, int) or count < 1:
            warnings.append(
                "%s: у заявки на «%s» количество должно быть целым "
                "положительным, получено %r — заявка не учтена."
                % (label, name or "?", count))
        elif count > components.MAX_EXTRA_COUNT:
            warnings.append(
                "%s: у заявки на «%s» количество %d больше предела %d — "
                "заявка не учтена."
                % (label, name, count, components.MAX_EXTRA_COUNT))

        if not str(row.get("why") or "").strip():
            warnings.append(
                "%s: не сказано, зачем дополнительные «%s» — заявка не учтена."
                % (label, name or "?"))

    return [], warnings


def flatten_text(variant, skip=()):
    """Весь пользовательский текст варианта одной строкой — для поиска слов.

    Служебные поля пропускаются: латинские идентификаторы библиотек ловились бы
    проверками как обычный текст.
    """
    parts = []
    for key, value in (variant or {}).items():
        if key in skip:
            continue
        parts.append(json.dumps(value, ensure_ascii=False))
    return " ".join(parts).lower()


def _stem(word):
    """Грубая основа слова — чтобы «3 ключа» ловилось по названию «Ключи».

    Отсечение двух последних букв с полом в четыре символа. Приём заведомо
    неточный: у коротких названий («Залы») окончание остаётся, и склонённая
    форма мимо. Это осознанный перекос в сторону молчания — ложное срабатывание
    стоит целой перегенерации модуля, а пропуск ловит аудитор своим пунктом
    no_component_quantities.
    """
    word = word.strip().lower()
    return word[:max(4, len(word) - 2)]


def quantity_hit(text, names=()):
    """Названо ли в тексте количество компонентов.

    `names` — имена, которые модуль сам дал артефактам. Без них проверка видит
    «три жетона», но пропускает «соберите 3 ключа» — а это тот же запрет,
    только выраженный через придуманное название.
    """
    stems = set(COMPONENT_STEMS)
    for name in names:
        if not isinstance(name, str):
            continue
        for word in name.split():
            stem = _stem(word)
            if len(stem) >= 4:
                stems.add(stem)

    pattern = NUMBER_RE + "(" + "|".join(re.escape(s) for s in sorted(stems)) + ")"
    return re.search(pattern, text, re.IGNORECASE)


def scary_words_in(text, age_min):
    """Пугающие слова, недопустимые для этой возрастной группы."""
    if age_min is None or age_min >= SCARY_AGE_LIMIT:
        return []
    return [word for word in SCARY_WORDS if word in text]
